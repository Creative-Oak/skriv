# Fetch LibreOffice's own Writer test documents into fidelity/corpus/libreoffice/.
#
# The files are not committed: LibreOffice core is MPL-2.0, but many test
# documents started life as Bugzilla attachments, so we fetch them from a
# pinned commit rather than redistribute them. The manifest records where each
# one came from.
#
# Usage: fidelity/scripts/fetch-lo-corpus.sh [max-files]
set -euo pipefail

REF="${LO_REF:-libreoffice-26.8.1.1}"
# The commit that tag points at; checked below so a moved tag can't change the corpus silently.
PINNED="${LO_COMMIT:-bf6ef2662401c7d6dce671ab4deb26ee0af3a7c1}"
MAX="${1:-1000}"
MAX_BYTES=$((3 * 1024 * 1024))

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WORK="$ROOT/fidelity/work/lo-core"
DEST="$ROOT/fidelity/corpus/libreoffice"
MANIFEST="$DEST/manifest.toml"

DIRS=(
  sw/qa/extras/odfexport/data
  sw/qa/extras/odfimport/data
  sw/qa/core/data/odt
  sw/qa/extras/layout/data
  sw/qa/extras/uiwriter/data
)

if [ ! -d "$WORK/.git" ]; then
  git clone --quiet --filter=blob:none --no-checkout --depth 1 --branch "$REF" \
    https://git.libreoffice.org/core "$WORK"
fi
got="$(git -C "$WORK" rev-parse HEAD)"
if [ "$got" != "$PINNED" ]; then
  echo "error: $REF resolved to $got, expected $PINNED" >&2
  exit 1
fi
git -C "$WORK" sparse-checkout set --no-cone $(printf '/%s/*.odt ' "${DIRS[@]}")
git -C "$WORK" checkout --quiet "$PINNED"

mkdir -p "$DEST"
find "$DEST" -name '*.odt' -delete
{
  echo "# Generated by fetch-lo-corpus.sh. Do not edit."
  echo "source = \"https://git.libreoffice.org/core\""
  echo "ref = \"$REF\""
  echo "commit = \"$PINNED\""
  echo "licence = \"MPL-2.0 (LibreOffice core repository licence; individual test files may originate from bug-report attachments)\""
  echo
} > "$MANIFEST"

# Take files round-robin across directories so the sample isn't all one area,
# skipping very large files; sorted so the selection is deterministic.
count=0
lists=()
for d in "${DIRS[@]}"; do
  f="$(mktemp)"
  find "$WORK/$d" -maxdepth 1 -name '*.odt' -size -${MAX_BYTES}c 2>/dev/null | LC_ALL=C sort > "$f"
  lists+=("$f")
done
row=1
while [ "$count" -lt "$MAX" ]; do
  progressed=0
  for f in "${lists[@]}"; do
    path="$(sed -n "${row}p" "$f")"
    [ -z "$path" ] && continue
    progressed=1
    rel="${path#"$WORK"/}"
    # sw/qa/extras/odfexport/data/foo.odt -> extras-odfexport__foo.odt
    area="$(dirname "$rel" | sed -e 's|^sw/qa/||' -e 's|/data$||' -e 's|/|-|g')"
    name="${area}__$(basename "$path")"
    cp "$path" "$DEST/$name"
    {
      echo "[[file]]"
      echo "name = \"$name\""
      echo "path = \"$rel\""
      echo
    } >> "$MANIFEST"
    count=$((count + 1))
    [ "$count" -ge "$MAX" ] && break
  done
  [ "$progressed" -eq 0 ] && break
  row=$((row + 1))
done
rm -f "${lists[@]}"
echo "fetched $count files into $DEST"
